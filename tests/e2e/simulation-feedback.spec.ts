test('simulation controls work from the keyboard and fit the narrowest supported screen', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 844 })
  await page.goto('/')
  const start = page.getByRole('button', { name: 'Start simulation', exact: true })
  await start.focus()
  await page.keyboard.press('Enter')
  const pause = page.getByRole('button', { name: 'Pause simulation', exact: true })
  await expect(pause).toBeFocused()
  await expect(page.locator('.simulation-session-count')).toHaveText('+7')
  await page.keyboard.press('Space')
  await expect(page.getByRole('button', { name: 'Resume simulation', exact: true })).toBeFocused()
  await expect(page.locator('.simulation-status')).toContainText('Simulation paused')
  const reset = page.getByRole('button', { name: 'Reset demo', exact: true })
  await reset.focus()
  await page.keyboard.press('Enter')
  await expect(start).toBeVisible()
  await expect(page.locator('.simulation-session-count')).toHaveText('+0')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  for (const control of [start, reset]) {
    const box = await control.boundingBox()
    expect(box).not.toBeNull()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(320)
    expect(box!.height).toBeGreaterThanOrEqual(44)
  }
})
