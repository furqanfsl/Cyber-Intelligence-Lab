import { expect, test, type Page } from '@playwright/test'
import { intelligence } from './fixtures.ts'

test.beforeEach(async ({ page }) => {
  await page.clock.install()
  await page.route('**/api/live-intel', (route) => route.fulfill({ json: intelligence }))
})

async function setHidden(page: Page, hidden: boolean) {
  await page.evaluate((value) => {
    Object.defineProperty(document, 'hidden', { configurable: true, value })
    Object.defineProperty(document, 'visibilityState', { configurable: true, value: value ? 'hidden' : 'visible' })
    document.dispatchEvent(new Event('visibilitychange'))
  }, hidden)
}

test('Start immediately confirms a running demo, adds events and preserves real intelligence', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.live-status-badge')).toHaveText('Sources current')
  const console = page.locator('.simulation-console')
  const status = page.locator('.simulation-status')
  await expect(console).toHaveAttribute('data-state', 'ready')
  await expect(status).toHaveAttribute('role', 'status')
  await expect(status).toContainText('Simulation ready')
  await expect(page.locator('.simulation-session-count')).toHaveText('+0')
  await expect(page.locator('.simulation-event-list li')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Reset demo', exact: true })).toBeDisabled()
  const selected = await page.locator('.queue-row[aria-pressed="true"]').getAttribute('aria-label')
  const records = await page.locator('.osint-list').allTextContents()

  await page.getByRole('button', { name: 'Start simulation', exact: true }).click()
  await expect(console).toHaveAttribute('data-state', 'running')
  await expect(status).toContainText('Simulation running')
  await expect(page.getByRole('button', { name: 'Pause simulation', exact: true })).toHaveAttribute('aria-pressed', 'true')
  // No clock advancement: the first result must be visible on the initial click.
  await expect(page.locator('.simulation-session-count')).toHaveText('+7')
  await expect(page.locator('.map-panel .map-readout data')).toHaveText('9,510')
  await expect(page.locator('.simulation-event-list li')).toHaveCount(1)
  await expect(page.locator('.simulation-event-list li').first()).toHaveAttribute('data-batch', '1')
  await expect(page.locator('.map-panel')).toContainText(/no (?:real )?traffic|not live traffic/i)
  expect(await page.locator('.osint-list').allTextContents()).toEqual(records)
  await expect(page.locator('.queue-row[aria-pressed="true"]')).toHaveAttribute('aria-label', selected!)
})

test('visible events advance by one batch with bounded history and no per-tick announcement', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Start simulation', exact: true }).click()
  const status = await page.locator('.simulation-status').textContent()
  for (let batch = 2; batch <= 8; batch++) {
    await page.clock.fastForward(2600)
    await expect(page.locator('.simulation-session-count')).toHaveText(`+${batch * 7}`)
    await expect(page.locator('.simulation-event-list li')).toHaveCount(Math.min(3, batch))
    await expect(page.locator('.simulation-event-list li').first()).toHaveAttribute('data-batch', String(batch))
  }
  await expect(page.locator('.simulation-status')).toHaveText(status!)
  const events = page.locator('.simulation-event-list')
  expect(await events.evaluate((element) => Boolean(element.closest('[role="status"], [role="alert"], [role="log"], [aria-live="polite"], [aria-live="assertive"]')))).toBe(false)
  expect(await events.locator('li').evaluateAll((rows) => rows.map((row) => row.getAttribute('data-batch')))).toEqual(['8', '7', '6'])
  const regionalSum = await page.locator('.map-panel .map-node data').evaluateAll((nodes) => nodes.reduce((sum, node) => sum + Number(node.textContent!.replaceAll(',', '')), 0))
  expect(regionalSum).toBe(9559)
  await expect(page.locator('.map-panel .map-readout data')).toHaveText('9,559')
})

test('Pause freezes session and event history; Resume continues without a new immediate batch', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Start simulation', exact: true }).click()
  await page.clock.fastForward(2600)
  await page.getByRole('button', { name: 'Pause simulation', exact: true }).click()
  await expect(page.locator('.simulation-console')).toHaveAttribute('data-state', 'paused')
  await expect(page.locator('.simulation-status')).toContainText('Simulation paused')
  const history = await page.locator('.simulation-event-list').textContent()
  await page.clock.fastForward(26_000)
  await expect(page.locator('.simulation-session-count')).toHaveText('+14')
  await expect(page.locator('.simulation-event-list')).toHaveText(history!)
  const resume = page.getByRole('button', { name: 'Resume simulation', exact: true })
  await expect(resume).toHaveAttribute('aria-pressed', 'false')
  await resume.click()
  await expect(page.locator('.simulation-console')).toHaveAttribute('data-state', 'running')
  await expect(page.locator('.simulation-session-count')).toHaveText('+14')
  await page.clock.fastForward(2600)
  await expect(page.locator('.simulation-session-count')).toHaveText('+21')
  await expect(page.locator('.simulation-event-list li').first()).toHaveAttribute('data-batch', '3')
})

